// Плотность модалки. `form` — тело с отступами (поля, текст); `list` — тело без боковых
// отступов, край держит Item (px-4), поэтому строки и разделители идут во всю ширину;
// `flush` — отступов нет вовсе, содержимое во всю площадь (iframe, карта, канвас).
// Значения адаптивные: на узком экране 16px, с sm (640px) — прежние 24px.
export type DialogLayout = 'form' | 'list' | 'flush';

export function dialogBodyClass(layout: DialogLayout = 'form'): string {
  // Пустая строка, а не 'p-0': дефолт не подмешивается вовсе. 'p-0' попал бы в
  // tailwind-merge и погасил бы только px-4 py-3, оставив sm:px-6 sm:py-4 живыми —
  // конфликты разрешаются внутри одного набора модификаторов, а вариант в CSS идёт
  // после базовой утилиты и побеждает.
  if (layout === 'flush') return '';
  if (layout === 'list') return 'px-0 py-2';
  return 'px-4 py-3 sm:px-6 sm:py-4';
}
