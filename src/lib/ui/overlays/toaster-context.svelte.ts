/**
 * z-index хоста тостов: `null` — дефолт sonner (`z-index: 999999999` на
 * `[data-sonner-toaster]`, то есть поверх всего), число — инлайновый стиль из
 * <ToasterMount>, который этот дефолт перебивает.
 *
 * По умолчанию тост НАД всем — так и надо: ошибка чаще всего прилетает из открытой
 * модалки, и там её нужно видеть и нажимать. Единственное исключение — окно, открытое
 * действием самого тоста (например, статья-подсказка): его надо читать, а не
 * разглядывать из-под тоста. Поэтому на это время хост «ныряет» под слой модалок и
 * возвращается, когда окно закрыли. Пробовать вычислить z по стеку модалок в момент
 * показа тоста не годится: оверлеи кита бывают и вне реестра (обычный `Dialog` с полосой
 * z-60/61), и тост тогда оказывается под тем, ради чего он и появился.
 *
 * 55 — выше контента `Dialog` по умолчанию (`z-50`), но ниже базы реестра модалок (60).
 * Это единственный `$state` на приложение: слой поверх кита, который рисует свои действия
 * внутри тоста, ныряет тостер через эти же функции, а не через копию.
 */
const DUCKED_Z = 55;

/** Дефолт svelte-sonner: `[data-sonner-toaster] { z-index: 999999999 }`. */
const SONNER_Z = 999999999;

export const toastLayer = $state<{ z: number | null }>({ z: null });

/**
 * Текущий z хоста тостов. Нужен всему, что обязано лечь ПОВЕРХ тоста — например меню,
 * открытому кнопкой внутри тоста: его контент портируется в `<body>`, а значит без явной
 * полосы уехал бы под тост, из которого его и открыли.
 */
export function toasterZ(): number {
  return toastLayer.z ?? SONNER_Z;
}

/** Увести хост тостов под слой модалок (на время окна, открытого из тоста). */
export function duckToasterUnderModals(): void {
  toastLayer.z = DUCKED_Z;
}

/** Вернуть хост тостов наверх. */
export function restoreToaster(): void {
  toastLayer.z = null;
}
